from ultralytics import YOLO

DATA_YAML = "/content/data.yaml"

# 1) 모델 로드
model = YOLO("yolov8n.pt")   # 또는 yolo11n.pt 등 사용중인 가중치

# 2) 학습 (train + val 자동 사용)
train_results = model.train(
    data=DATA_YAML,
    epochs=30,
    imgsz=640,
    batch=16,
    name="exp_train"
)

# 3) 최종 테스트 평가 (test split)
test_metrics = model.val(
    data=DATA_YAML,
    split="test"
)

print("TEST metrics:", test_metrics)

